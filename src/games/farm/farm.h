#ifndef GAMES_FARM_FARM_H
#define GAMES_FARM_FARM_H

#include <Arduino.h>
#include "core/game.h"
#include "core/display.h"
#include "art.h"

// SPROUT - a tiny top-down farm in landscape mode (320x170).
//
// Tend an 8x4 field farm. One in-game day lasts ~10 seconds of real
// time. Plants grow one stage per day, but only when they were
// watered that day - neglect a plant two days in a row and it
// withers. Harvest ripe crops for gold.
//
// Controls (2 buttons):
//   hold A        = walk in the facing direction
//   A short       = turn (up -> right -> down -> left)
//   B short       = act on the plot under the farmer
//                   (dig soil / plant seed / water / harvest / clear)
//   B long        = back to the menu
//   Title: any press = start
//
// Sprite art is generated by tools/gen_farm_art.py into art.h/art.cpp
// (procedural Super-Retro-World-style pixel art; drop a 16x16 PNG
// named e.g. Crop3.png into assets/farm/ to override a sprite).
class FarmGame : public Game {
public:
  const char* name() const override { return "Sprout"; }
  void init() override;
  void update(const InputState& in, uint32_t dtMs) override;
  void draw() override;
  void quit() override;

  enum Phase : uint8_t { PH_TITLE, PH_PLAY };

  // Sprite ids - order must match kSprites[] in art.cpp.
  enum SpriteId : uint8_t {
    SP_SOIL = 0, SP_TILLED, SP_SPROUT, SP_CROP1, SP_CROP2, SP_CROP3,
    SP_WITHERED, SP_CURSOR, SP_FARMER, SP_WATERCAN, SP_COIN,
    SP_PLOT, SP_HOUSE, SP_COUNT
  };

  // Plot states
  enum FieldState : uint8_t {
    FS_SOIL = 0,   // fallow: dig it
    FS_TILLED,     // tilled: plant a seed
    FS_GROWING,    // seedling growing (stage 0..2)
    FS_READY,      // ripe: harvest
    FS_WITHERED    // dried out: clear it
  };

  struct Field {
    uint8_t state    = FS_SOIL;
    uint8_t stage    = 0;     // growth stage while FS_GROWING (0..2)
    bool    watered  = false; // watered today?
    uint8_t dryDays  = 0;     // consecutive days without water
  };

  static constexpr uint8_t  COLS      = 8;
  static constexpr uint8_t  ROWS      = 4;
  static constexpr uint8_t  FIELD_COUNT = COLS * ROWS;
  static constexpr uint32_t DAY_MS    = 10000;  // one in-game day
  static constexpr uint32_t MOVE_MS   = 90;     // 1 px per walk step
  static constexpr uint16_t HARVEST_VALUE = 5;  // gold per crop
  static constexpr uint8_t  GROW_STAGES    = 3; // stages until ripe
  static constexpr uint8_t  DRY_DAYS_TO_WITHER = 2;

  void startGame();
  void doAction();
  void advanceDay();
  void flash(const char* msg);

  uint8_t fieldAt(int16_t px, int16_t py) const;
  const char* fieldInfo(uint8_t idx, char* buf, size_t len) const;

  void drawTitle(TFT_eSprite& fb);
  void drawScene(TFT_eSprite& fb);
  void drawHud(TFT_eSprite& fb);
  void drawPanel(TFT_eSprite& fb);

  Phase    phase_   = PH_TITLE;

  Field    fields_[FIELD_COUNT];
  int16_t  px_      = 0;      // farmer position (top-left, px)
  int16_t  py_      = 0;
  uint8_t  dir_     = 2;      // 0=up 1=right 2=down 3=left
  uint32_t moveMs_  = 0;      // accumulator for walk steps

  uint16_t day_     = 0;      // in-game days elapsed
  uint32_t dayMs_   = 0;      // ms toward the next day
  uint16_t gold_    = 0;
  uint16_t best_    = 0;      // highscore (RAM only)

  bool     rain_    = false;  // rain event (auto-waters all crops)
  uint32_t rainUntil_ = 0;

  char     msg_[32] = "";     // transient feedback message
  uint32_t msgMs_   = 0;

  // Full-screen framebuffer (320x170x16 bit ~106 KB, in PSRAM on the S3)
  TFT_eSprite fb_{&gfx.tft()};
};

#endif
